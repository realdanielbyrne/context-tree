MIGRATION = """\
# minicart v2 migration guide

v2 replaces v1 completely. After the migration NO public function may
accept the old positional call shape and NO returned dict may carry the
old key names. `python3 smoke.py` must print SMOKE OK.

## Dict shape renames

    item   v1: {"sku", "name", "price", "qty"}
           v2: {"sku", "name", "unit_price_cents", "quantity"}
    order  v1: {"id", "items", "total"}
           v2: {"order_id", "lines", "total_cents"}

## catalog.py

`make_item(*, sku, name, unit_price_cents, quantity) -> item`
- all four parameters keyword-only (a positional call raises TypeError);
- unit_price_cents and quantity must be ints >= 0; raise ValueError
  otherwise.

`find_item(items, *, sku) -> item`
- sku is keyword-only;
- raises KeyError(sku) when no item matches (v1 returned None).

## pricing.py

`line_total(item) -> int`
- item["unit_price_cents"] * item["quantity"].

`apply_discount(total_cents, *, percent) -> int`
- percent is keyword-only;
- the discounted total is rounded HALF-UP to the nearest cent (v1
  truncated):

      apply_discount(995, percent=15) == 846   # 845.75 rounds up
      apply_discount(999, percent=15) == 849   # 849.15 rounds down
      apply_discount(99, percent=50)  == 50    # 49.5  rounds up

## orders.py

`build_order(*, order_id, lines, discount_percent=0) -> order`
- all parameters keyword-only;
- "lines" holds the given list; "total_cents" is
  apply_discount(sum of line_total over lines, percent=discount_percent).

`order_summary(order) -> str`
- exactly "order <order_id>: <n> lines = <total_cents>c", e.g.
  "order po-7: 2 lines = 1150c".

## report.py (call site)

`build_report(order) -> str`
- first line: order_summary(order);
- then one line per order line, in the given order, exactly
  "  <sku> x<quantity> @ <unit_price_cents>c = <line total>c"
  (two leading spaces), e.g. "  a-1 x3 @ 250c = 750c";
- lines joined with a single newline, no trailing newline.

## restock.py (call site)

`needs_restock(items, sku, *, threshold) -> bool`
- threshold is keyword-only;
- True iff the item's quantity < threshold;
- an unknown sku propagates find_item's KeyError (v1 returned False).

`low_stock(items, *, threshold) -> list[str]`
- threshold is keyword-only;
- the skus with quantity < threshold, sorted alphabetically (v1 kept
  input order).
"""

