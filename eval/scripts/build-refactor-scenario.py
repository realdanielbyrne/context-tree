def write_files(root: pathlib.Path, files: dict) -> None:
    for name, content in files.items():
        (root / name).write_text(content, encoding="utf-8")


def run(root: pathlib.Path, script: str) -> subprocess.CompletedProcess:
    return subprocess.run(
        [sys.executable, script], capture_output=True, text=True, cwd=str(root)
    )


def upsert_row(row: dict) -> None:
    """Append-or-replace this script's row by id; rows stay sorted by id so
    running the diverse builders in any order yields byte-identical output."""
    JSONL.parent.mkdir(parents=True, exist_ok=True)
    rows = []
    if JSONL.exists():
        for line in JSONL.read_text(encoding="utf-8").splitlines():
            if line.strip():
                rows.append(json.loads(line))
    rows = [r for r in rows if r.get("id") != row["id"]]
    rows.append(row)
    rows.sort(key=lambda r: r["id"])
    JSONL.write_text(
        "".join(json.dumps(r, ensure_ascii=False) + "\n" for r in rows),
        encoding="utf-8",
    )


def main() -> None:
    row = {
        "id": "sw-3-refactor",
        "task": TASK,
        "files": {
            "catalog.py": V1_CATALOG,
            "pricing.py": V1_PRICING,
            "orders.py": V1_ORDERS,
            "report.py": V1_REPORT,
            "restock.py": V1_RESTOCK,
            "smoke.py": SMOKE,
            "MIGRATION.md": MIGRATION,
            "README.md": README,
        },
        "judge_command": "python3 run_hidden_tests.py",
        "judge_files": {
            "run_hidden_tests.py": RUNNER,
            "hidden_test_catalog.py": HIDDEN_CATALOG,
            "hidden_test_pricing.py": HIDDEN_PRICING,
            "hidden_test_orders.py": HIDDEN_ORDERS,
            "hidden_test_report.py": HIDDEN_REPORT,
            "hidden_test_restock.py": HIDDEN_RESTOCK,
        },
    }

    with tempfile.TemporaryDirectory() as tmp:
        tmp_path = pathlib.Path(tmp)
        write_files(tmp_path, {**row["files"], **row["judge_files"]})

        buggy = run(tmp_path, "run_hidden_tests.py")
        print("=== V1 judge exit=%s ===" % buggy.returncode)
        print((buggy.stdout + buggy.stderr)[-1200:])
        buggy_smoke = run(tmp_path, "smoke.py")

        write_files(
            tmp_path,
            {
                "catalog.py": V2_CATALOG,
                "pricing.py": V2_PRICING,
                "orders.py": V2_ORDERS,
                "report.py": V2_REPORT,
                "restock.py": V2_RESTOCK,
            },
        )
        fixed = run(tmp_path, "run_hidden_tests.py")
        print("=== V2 judge exit=%s ===" % fixed.returncode)
        print((fixed.stdout + fixed.stderr)[-400:])
        fixed_smoke = run(tmp_path, "smoke.py")

    assert buggy.returncode != 0, "legacy v1 files should FAIL the hidden v2 suite"
    # Every hidden module must fail on its own against v1 — a module the suite
    # cannot distinguish from v2 would measure nothing.
    for name in HIDDEN_MODULE_NAMES:
        assert ("[%s] FAIL" % name) in buggy.stdout, (
            "hidden suite never catches the un-migrated %s" % name
        )
    assert buggy_smoke.returncode != 0, "smoke.py should fail against v1"
    assert fixed.returncode == 0, "migrated reference should PASS the hidden suite"
    assert "SMOKE OK" in fixed_smoke.stdout, "smoke.py should print SMOKE OK on v2"

    upsert_row(row)
    total_chars = (
        len(row["task"])
        + sum(len(c) for c in row["files"].values())
        + sum(len(c) for c in row["judge_files"].values())
    )
    print(
        "OK: sw-3-refactor upserted; v1 FAILS (all %d hidden modules) / v2 PASSES; "
        "%d chars total content" % (len(HIDDEN_MODULE_NAMES), total_chars)
    )


if __name__ == "__main__":
    main()
