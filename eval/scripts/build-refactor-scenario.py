V2_CATALOG = '''\
"""minicart catalog — items and lookup (v2 API, per MIGRATION.md)."""


def make_item(*, sku, name, unit_price_cents, quantity):
    if not isinstance(unit_price_cents, int) or unit_price_cents < 0:
        raise ValueError("unit_price_cents must be an int >= 0")
    if not isinstance(quantity, int) or quantity < 0:
        raise ValueError("quantity must be an int >= 0")
    return {
        "sku": sku,
        "name": name,
        "unit_price_cents": unit_price_cents,
        "quantity": quantity,
    }


def find_item(items, *, sku):
    for item in items:
        if item["sku"] == sku:
            return item
    raise KeyError(sku)
'''

